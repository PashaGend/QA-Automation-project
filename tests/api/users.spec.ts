import { test, expect, APIRequestContext } from '@playwright/test';
import { REST_URL, SUPABASE_ANON_KEY } from '../config';

test('seeded admin user can be found by phone', async ({ request }) => {
  const res = await request.get(`${REST_URL}/users?phone=eq.0548009108`, {
    headers: {
      apikey: SUPABASE_ANON_KEY,
      Authorization: `Bearer ${SUPABASE_ANON_KEY}`,
    },
  });

  expect(res.status()).toBe(200);
  const data = await res.json();
  expect(data).toHaveLength(1);
  expect(data[0]).toMatchObject({
    phone: '0548009108',
    nickname: 'פאשה',
  });
});

test('creating a user with a valid phone and nickname returns the created row', async ({
  request,
}) => {
  // phones always start with 052 so this file's test data can never collide with another spec file's or with the seeded admin (0548009108)
  const phone = '05' + Math.floor(20000000 + Math.random() * 10000000);
  const nickname = 'test_user_' + phone;

  const res = await request.post(REST_URL + '/users', {
    headers: {
      apikey: SUPABASE_ANON_KEY,
      Authorization: 'Bearer ' + SUPABASE_ANON_KEY,
      'Content-Type': 'application/json',
      Prefer: 'return=representation',
    },
    data: { phone: phone, nickname: nickname },
  });

  expect(res.status()).toBe(201);
  const data = await res.json();
  expect(data).toHaveLength(1);
  expect(data[0]).toMatchObject({ phone: phone, nickname: nickname });
});

test('creating a user with a phone that is already in use returns a unique violation', async ({
  request,
}) => {
  const phone = '05' + Math.floor(20000000 + Math.random() * 10000000);
  const headers = {
    apikey: SUPABASE_ANON_KEY,
    Authorization: 'Bearer ' + SUPABASE_ANON_KEY,
    'Content-Type': 'application/json',
  };

  await request.post(REST_URL + '/users', {
    headers: headers,
    data: { phone: phone, nickname: 'first_nickname' },
  });
  const res = await request.post(REST_URL + '/users', {
    headers: headers,
    data: { phone: phone, nickname: 'second_nickname' },
  });

  expect(res.status()).toBe(409);
  const error = await res.json();
  expect(error.code).toBe('23505');
});

