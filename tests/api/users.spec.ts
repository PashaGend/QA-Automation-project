test('fetching a user by a phone that does not exist returns an empty array, not an error', async ({
  request,
}) => {
  // 0500000000 can never be generated by the random test phones below (Math.random always yields an 8-digit suffix >= 10000000)
  const res = await request.get(REST_URL + '/users?phone=eq.0500000000', {
    headers: {
      apikey: SUPABASE_ANON_KEY,
      Authorization: 'Bearer ' + SUPABASE_ANON_KEY,
    },
  });

  expect(res.status()).toBe(200);
  const data = await res.json();
  expect(data).toEqual([]);
});

test('deleting an existing user returns the deleted row', async ({ request }) => {
  const phone = '05' + Math.floor(20000000 + Math.random() * 10000000);
  const nickname = 'test_user_' + phone;
  const headers = {
    apikey: SUPABASE_ANON_KEY,
    Authorization: 'Bearer ' + SUPABASE_ANON_KEY,
    'Content-Type': 'application/json',
  };

  await request.post(REST_URL + '/users', {
    headers: headers,
    data: { phone: phone, nickname: nickname },
  });

  const res = await request.delete(REST_URL + '/users?phone=eq.' + phone, {
    headers: { ...headers, Prefer: 'return=representation' },
  });

  expect(res.status()).toBe(200);
  const data = await res.json();
  expect(data).toHaveLength(1);
  expect(data[0]).toMatchObject({ phone: phone, nickname: nickname });
});

